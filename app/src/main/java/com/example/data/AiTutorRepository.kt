class AiTutorRepository {

    suspend fun getTutorReply(userMessage: String, userClass: Int): String {
        delay(600) // Realistic thoughtful delay

        val msg = userMessage.trim().lowercase()

        return when {
            msg.contains("সালোকসংশ্লেষণ") || msg.contains("photosynthesis") ->
                "সালোকসংশ্লেষণ (Photosynthesis) হলো এমন একটি জৈবরাসায়নিক প্রক্রিয়া, যাতে সবুজ উদ্ভিদ সূর্যালোক ও ক্লোরোফিলের সহায়তায় কার্বন ডাই অক্সাইড (CO₂) এবং পানি (H₂O) ব্যবহার করে শর্করা (গ্লুকোজ) প্রস্তুত করে এবং উপজাত হিসেবে অক্সিজেন নির্গমন করে!\n\nরাসায়নিক বিক্রিয়া:\n6CO₂ + 12H₂O + সূর্যালোক/ক্লোরোফিল → C₆H₁₂O₆ + 6O₂ + 6H₂O\n\nকোন অংশ বুঝতে সমস্যা হচ্ছে বলো?"

            msg.contains("পিথাগোরাস") || msg.contains("pythagoras") ->
                "পিথাগোরাসের উপপাদ্য কেবল সমকোণী ত্রিভুজের জন্য প্রযোজ্য:\n\n'একটি সমকোণী ত্রিভুজের অতিভুজের ওপর অঙ্কিত বর্গক্ষেত্রের ক্ষেত্রফল অপর দুই বাহুর ওপর অঙ্কিত বর্গক্ষেত্রদ্বয়ের ক্ষেত্রফলের সমষ্টির সমান।'\n\nসূত্র:\nঅতিভুজ² = লম্ব² + ভূমি² (c² = a² + b²)\n\nযেমন: বাহু ৩ ও ৪ হলে অতিভুজ হবে √(৯ + ১৬) = ৫।"

            msg.contains("মুক্তিযুদ্ধ") || msg.contains("১৯৭১") ->
                "১৯৭১ সালের মহান মুক্তিযুদ্ধ আমাদের গৌরবের ইতিহাস। ২৫শে মার্চ কালরাতে পাকিস্তানি হানাদার বাহিনী নিরস্ত্র বাঙালির ওপর বর্বরোচিত আক্রমণ চালালে ২৬শে মার্চ বঙ্গবন্ধু শেখ মুজিবুর রহমান স্বাধীনতার ঘোষণা দেন। দীর্ঘ ৯ মাসের রক্তক্ষয়ী সংগ্রাম ও ৩০ লাখ শহীদের আত্মত্যাগের বিনিময়ে ১৬ই ডিসেম্বর আমরা চূড়ান্ত বিজয় অর্জন করি।"

            msg.contains("সন্ধি") || msg.contains("সমাস") ->
                "সন্ধি মানে ধ্বনির মিলন। যেমন: বিদ্যা + আলয় = বিদ্যালয়। আর সমাস মানে পদের মিলন। যেমন: সিংহ চিহ্নিত আসন = সিংহাসন। সন্ধিতে ধ্বনি পরিবর্তিত বা লুপ্ত হয়, আর সমাসে একাধিক পদ মিলে একটি নতুন পদ তৈরি করে।"

            msg.contains("পড়া মনে থাকে না") || msg.contains("পড়ার টিপস") ->
                "পড়া মনে রাখার জন্য ৩টি বৈজ্ঞানিক কৌশল:\n১. সক্রিয় পুনরাবৃত্তি (Active Recall): পড়ার পর না দেখে নিজে নিজে মনে করার চেষ্টা করো।\n২. স্পেসড রিপিটেশন (Spaced Repetition): ১ দিন, ৩ দিন ও ৭ দিন পর রিভিশন দাও।\n৩. কাউকে শেখাও (Feynman Technique): সহজ ভাষায় কাউকে বিষয়টি বুঝিয়ে দাও।"

            else ->
                "চমৎকার প্রশ্ন! বিষয়টি খুব সহজ: তুমি তোমার পাঠ্যবইয়ের মূল সূত্র ও ধারণাগুলো প্রথমে ভালো করে পড়বে, তারপর খাতায় লিখে অনুশীলন করবে। এতে যেকোনো জটিল সমস্যা সমাধান করা সহজ হয়ে যাবে। আরও কোনো প্রশ্ন থাকলে বলো, মশাই বুঝিয়ে দেব!"
        }
    }

