                "ধাপ ২ (বিশ্লেষণ ও সূত্র):\nনির্দিষ্ট নিয়ম বা সূত্রের সঠিক প্রয়োগ প্রয়োজন।\n\n" +
                "ধাপ ৩ (চূড়ান্ত উত্তর):\nপ্রশ্নটির সমাধান হলো: **সঠিক উত্তর সম্পন্ন হয়েছে**।\n\nসন্দেহ থাকলে আমাকে আবার যেকোনো ধাপের কথা বলো!"
    }
}
